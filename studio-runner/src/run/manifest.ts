/**
 * The terminal result manifest (story 10.14 AC-6, AC-7a; architecture §5.3, §9.2).
 *
 * ## Why it exists
 *
 * §5.3: *"Before delivery, runner writes a redacted terminal result manifest to a deterministic
 * Sonic key."* A delivery can be lost; the object cannot. When the API's reaper reaches an
 * execution it has no terminal report for, it reads this object at the key it derives from
 * immutable execution identity and applies the **real** outcome instead of a timeout verdict. That
 * is the whole point of writing it before the result is delivered rather than after.
 *
 * ## What it carries
 *
 * §5.3 names five things: *"attempt/revision identity, result, timings, runtime versions, and
 * evidence state"*. All five are here. The Java `ResultManifest` that reads it carries the same
 * components under the same names, and the agreement between the two is proven by **one committed
 * fixture generated by this serializer** rather than by two hand-maintained copies in two languages
 * — the arrangement ADR-002 §15.6 names as the cause of INT-4.
 *
 * ## What it must never carry
 *
 * §9.2: *"Never persist them in jobs, retry queues, manifests or diagnostics."* No resolved
 * variable and no resolved secret reaches these bytes. {@link serializeResultManifest} redacts
 * **twice** and the order is deliberate: every string leaf first, so a value carrying a character
 * JSON escapes cannot slide past the second pass, then the finished text, so a value that reached
 * the document through a number, a key or a concatenation is still caught. The assertion that
 * proves it is made on the bytes handed to the store, never on the object the serializer was given
 * (AC-6, AC-23).
 *
 * ## Serialized once
 *
 * The bytes are produced once and the same `Uint8Array` is handed to every retry attempt — the
 * discipline `reportClient.deliverTerminal` already applies to the `FINAL` body, for the same
 * reason: a bounded retry must retain one bounded body and not re-render it per attempt.
 */
import type { Redactor } from '../executor/redaction.js';

/** The schema version these bytes are written under. Read by the API before anything else. */
export const RESULT_MANIFEST_SCHEMA_VERSION = 1;

/** `application/json`, stated once so the store call and the fixture cannot disagree. */
export const RESULT_MANIFEST_CONTENT_TYPE = 'application/json';

/** The evidence vocabulary the manifest records. The same words the `FINAL` carries (§6.1). */
export type ManifestEvidenceState = 'PENDING' | 'STORED' | 'FAILED' | 'UNAVAILABLE';

/**
 * The manifest body, exactly as it is serialized.
 *
 * Property order here is the property order on the wire, because `JSON.stringify` preserves
 * insertion order — which is what makes the committed fixture a byte-level assertion rather than a
 * structural one.
 */
export interface ResultManifestBody {
  readonly schemaVersion: number;
  // ── Identity (§5.3 "attempt/revision identity") ────────────────────────────────────────────
  readonly executionId: string;
  readonly attemptId: string;
  readonly revisionId: string;
  readonly artifactHash: string;
  readonly runnerInstanceId: string;
  // ── Result ────────────────────────────────────────────────────────────────────────────────
  readonly outcome: 'PASSED' | 'FAILED' | 'ERROR';
  readonly errorCode: string | null;
  readonly errorMessage: string | null;
  // ── Timings ───────────────────────────────────────────────────────────────────────────────
  readonly browserStartedAt: string | null;
  readonly endedAt: string;
  readonly durationMs: number | null;
  // ── Runtime versions ──────────────────────────────────────────────────────────────────────
  readonly runtimeVersions: Readonly<Record<string, string>>;
  // ── Evidence state ────────────────────────────────────────────────────────────────────────
  readonly videoKey: string;
  readonly manifestKey: string;
  readonly evidenceState: ManifestEvidenceState;
  readonly evidencePartial: boolean;
}

export interface ResultManifestInput {
  readonly executionId: string;
  readonly attemptId: string;
  readonly revisionId: string;
  readonly artifactHash: string;
  readonly runnerInstanceId: string;
  readonly outcome: { readonly result: 'PASSED' | 'FAILED' | 'ERROR'; readonly errorCode: string | null; readonly errorMessage: string | null };
  readonly browserStartedAt: string | null;
  readonly endedAt: string;
  readonly runtimeVersions: Readonly<Record<string, unknown>>;
  readonly videoKey: string;
  readonly manifestKey: string;
  readonly evidenceState: ManifestEvidenceState;
  readonly evidencePartial: boolean;
}

/**
 * Builds the manifest body.
 *
 * `durationMs` is browser execution time and is derived from the two instants this runner already
 * holds — never from a third clock reading taken here, which would be the second origin §11.5
 * forbids. It is `null` until the browser actually started, because there is nothing to measure
 * from.
 *
 * Nothing in this function reads `outcome` to decide an evidence field, or an evidence field to
 * decide an outcome (§6.1, ADR-002 §17.4). `evidencePartial` is carried in verbatim.
 */
export function buildResultManifest(input: ResultManifestInput): ResultManifestBody {
  return {
    schemaVersion: RESULT_MANIFEST_SCHEMA_VERSION,
    executionId: input.executionId,
    attemptId: input.attemptId,
    revisionId: input.revisionId,
    artifactHash: input.artifactHash,
    runnerInstanceId: input.runnerInstanceId,
    outcome: input.outcome.result,
    errorCode: input.outcome.errorCode,
    errorMessage: input.outcome.errorMessage,
    browserStartedAt: input.browserStartedAt,
    endedAt: input.endedAt,
    durationMs: durationMs(input.browserStartedAt, input.endedAt),
    runtimeVersions: stringValues(input.runtimeVersions),
    videoKey: input.videoKey,
    manifestKey: input.manifestKey,
    evidenceState: input.evidenceState,
    evidencePartial: input.evidencePartial,
  };
}

/**
 * Serializes the manifest once, redacted, as UTF-8 bytes.
 *
 * Two passes, in this order:
 *
 * 1. every string leaf, so a value containing a quote or a backslash is scrubbed **before** JSON
 *    escaping can hide it from a text search;
 * 2. the finished document, so a value that reached it through a key, a concatenation or a
 *    non-string leaf is still caught.
 *
 * The second pass alone would miss (1); the first alone would miss (2). Both are cheap.
 */
export function serializeResultManifest(
  manifest: ResultManifestBody,
  redactor: Redactor,
): Uint8Array {
  const scrubbed = redactStrings(manifest, redactor) as ResultManifestBody;
  const text = redactor.redact(JSON.stringify(scrubbed));
  return new TextEncoder().encode(text);
}

/** Walks the document and redacts every string leaf and every key. */
function redactStrings(value: unknown, redactor: Redactor): unknown {
  if (typeof value === 'string') return redactor.redact(value);
  if (Array.isArray(value)) return value.map((entry) => redactStrings(entry, redactor));
  if (value !== null && typeof value === 'object') {
    const result: Record<string, unknown> = {};
    for (const [key, entry] of Object.entries(value)) {
      result[redactor.redact(key)] = redactStrings(entry, redactor);
    }
    return result;
  }
  return value;
}

/**
 * Runtime versions as strings.
 *
 * The record is open on the wire (§4.6) and a non-string value would make the committed fixture
 * ambiguous, so every entry is rendered here and the rendering is the one the API reads.
 */
function stringValues(source: Readonly<Record<string, unknown>>): Record<string, string> {
  const result: Record<string, string> = {};
  for (const key of Object.keys(source).sort()) {
    const value = source[key];
    if (value === undefined || value === null) continue;
    // `runtimeVersions` is an open record on the wire (§4.6). A non-string entry is rendered
    // through JSON rather than through `String`, so an object never becomes "[object Object]" and
    // the committed fixture stays unambiguous.
    result[key] = typeof value === 'string' ? value : JSON.stringify(value);
  }
  return result;
}

function durationMs(browserStartedAt: string | null, endedAt: string): number | null {
  if (browserStartedAt === null) return null;
  const started = Date.parse(browserStartedAt);
  const ended = Date.parse(endedAt);
  if (Number.isNaN(started) || Number.isNaN(ended)) return null;
  const elapsed = ended - started;
  return elapsed < 0 ? null : elapsed;
}
