/**
 * Story 10.14 AC-6, AC-7a — the terminal result manifest: what it carries, and what it must not.
 *
 * ## The fixture is the contract this body does not have
 *
 * The manifest is a runner-produced body the API deserializes, and it is **not** declared in the
 * frozen contract — every other such body is (ADR-002 §6.2). AC-7b escalates that to @architect and
 * this story does not add a schema on its own authority. What a story *may* do is make the two
 * sides share one artefact instead of two hand-maintained copies in two languages, which is the
 * arrangement §15.6 names as the cause of INT-4. So: **one fixture, generated by this serializer,
 * committed once.** This file asserts the serializer still produces those bytes; `ResultManifestFixtureTest`
 * in the backend deserializes the same file through `ResultManifest` and asserts every field.
 *
 * ## The canaries are an experiment, not a `doesNotContain`
 *
 * Story 10.5's gate found redaction assertions that *"cannot fail … the tests are vacuously true"*
 * because the canary was never in the request. Each shape below is **placed** so that it genuinely
 * reaches the serializer through a different route, each is asserted absent from the bytes captured
 * at the **store boundary** rather than from the object the serializer was handed, and each ships
 * with its own falsifying mutation recorded in the story's Dev Agent Record.
 */
