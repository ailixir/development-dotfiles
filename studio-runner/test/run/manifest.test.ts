function serialize(input: ResultManifestInput, redactor = NULL_REDACTOR): string {
  return new TextDecoder().decode(serializeResultManifest(buildResultManifest(input), redactor));
}

// ── AC-7a: §5.3's five contents, and the shared fixture ──────────────────────────────────────

describe('AC-7a — the manifest carries what §5.3 names', () => {
  it('carries attempt/revision identity, result, timings, runtime versions and evidence state', () => {
    const manifest = buildResultManifest(FIXTURE_INPUT);

    // Identity — absent from the Java record until this story widened it.
    expect(manifest.executionId).toBe(FIXTURE_INPUT.executionId);
    expect(manifest.attemptId).toBe(FIXTURE_INPUT.attemptId);
    expect(manifest.revisionId).toBe(FIXTURE_INPUT.revisionId);
    expect(manifest.artifactHash).toBe(FIXTURE_INPUT.artifactHash);
    // Result.
    expect(manifest.outcome).toBe('ERROR');
    expect(manifest.errorCode).toBe('TIMEOUT');
    // Timings — derived from the two instants the runner already holds, never a third reading.
    expect(manifest.browserStartedAt).toBe('2026-09-11T10:00:02.000Z');
    expect(manifest.endedAt).toBe('2026-09-11T10:02:02.500Z');
    expect(manifest.durationMs).toBe(120_500);
    // Runtime versions — also absent from the Java record until this story.
    expect(manifest.runtimeVersions.playwright).toBe('1.63.0');
    expect(manifest.runtimeVersions.chromium).toBe('141.0.7390.37');
    // Evidence state.
    expect(manifest.evidenceState).toBe('STORED');
    expect(manifest.evidencePartial).toBe(true);
    expect(manifest.schemaVersion).toBe(RESULT_MANIFEST_SCHEMA_VERSION);
  });

  it('still produces the committed fixture byte for byte', () => {
    // The backend deserializes this same file through `ResultManifest`. If this goes red, one of
    // the two sides moved and the other did not — which is exactly what the fixture is for.
    // CRLF -> LF first: a CRLF (Windows) checkout of the fixture is the same bytes on an LF one.
    expect(serialize(FIXTURE_INPUT)).toBe(readFileSync(FIXTURE, 'utf8').replace(/\r\n/gu, '\n').trimEnd());
  });

  it('has no browser duration before the browser started', () => {
    const manifest = buildResultManifest({ ...FIXTURE_INPUT, browserStartedAt: null });

    expect(manifest.browserStartedAt).toBeNull();
    expect(manifest.durationMs).toBeNull();
  });

  it('never derives an evidence field from the outcome or an outcome from an evidence field', () => {
    // §17.4's two directions, on the manifest this time.
    const timedOutButWhole = buildResultManifest({ ...FIXTURE_INPUT, evidencePartial: false });
    const passedButTruncated = buildResultManifest({
      ...FIXTURE_INPUT,
      outcome: { result: 'PASSED', errorCode: null, errorMessage: null },
      evidencePartial: true,
    });

    expect(timedOutButWhole.outcome).toBe('ERROR');
    expect(timedOutButWhole.errorCode).toBe('TIMEOUT');
    expect(timedOutButWhole.evidencePartial).toBe(false);
    expect(passedButTruncated.outcome).toBe('PASSED');
    expect(passedButTruncated.evidencePartial).toBe(true);
  });
});

// ── AC-6: the canary experiment, on the bytes at the store boundary ──────────────────────────

/**
 * Three shapes, chosen because each defeats a source scan.
 *
 * A reviewer grepping this module for the resolved values would find none of these: the first
 * arrives through a local whose name says nothing about secrets, the second rides a throwable's
 * message into `errorMessage`, and the third is inside a runtime-version string, which is a field
 * nobody thinks of as carrying user data.
 */
const CANARIES = {
  innocentLocal: 'canary-through-an-innocent-local-4f2a91',
  throwableMessage: 'canary-on-a-throwable-message-b7c3e0',
  runtimeVersion: 'canary-inside-a-version-string-d19f55',
} as const;

async function bytesAtTheStoreBoundary(input: ResultManifestInput, values: string[]): Promise<string> {
  const redactor = createRedactor(values);
  const store = createFakeObjectStore();
  let clock = 0;
  const ports: EvidenceUploadPorts = {
    store: store.client,
    fileSystem: {
      stat: () => Promise.resolve({ size: 1 }),
      readFile: () => Promise.reject(new Error('never')),
    },
    bounds: { maxAttempts: 2, windowMs: 10_000, backoffMs: 0 },
    now: () => (clock += 1),
    sleep: () => Promise.resolve(),
    redactor,
  };

  const bytes = serializeResultManifest(buildResultManifest(input), redactor);
  const written = await writeResultManifest(
    ports,
    openEvidenceWindow(ports),
    input.manifestKey,
    bytes,
    RESULT_MANIFEST_CONTENT_TYPE,
  );
  expect(written.ok).toBe(true);

  const stored = store.objectAt(input.manifestKey);
  expect(stored).toBeDefined();
  // The bytes the store received — not the object the serializer was given (AC-23).
  return new TextDecoder().decode(stored ?? new Uint8Array());
}

describe('AC-6 — no resolved value reaches the manifest, proven on the stored bytes', () => {
  /** The control. Without it every `not.toContain` below is vacuously true. */
  it('the three canaries really are in the run before redaction', () => {
    const unredacted = serialize(inputWithCanaries(), NULL_REDACTOR);

    expect(unredacted).toContain(CANARIES.innocentLocal);
    expect(unredacted).toContain(CANARIES.throwableMessage);
    expect(unredacted).toContain(CANARIES.runtimeVersion);
  });

  it('shape 1 — a value reaching the manifest through an innocently named local', async () => {
    const stored = await bytesAtTheStoreBoundary(inputWithCanaries(), [CANARIES.innocentLocal]);

    expect(stored).not.toContain(CANARIES.innocentLocal);
    expect(stored).toContain('[REDACTED]');
  });

  it('shape 2 — a value carried on a throwable message that lands in errorMessage', async () => {
    const stored = await bytesAtTheStoreBoundary(inputWithCanaries(), [CANARIES.throwableMessage]);

    expect(stored).not.toContain(CANARIES.throwableMessage);
  });

  it('shape 3 — a value inside a runtime-version string', async () => {
    const stored = await bytesAtTheStoreBoundary(inputWithCanaries(), [CANARIES.runtimeVersion]);

    expect(stored).not.toContain(CANARIES.runtimeVersion);
  });

  it('scrubs all three at once, and the document is still valid JSON', async () => {
    const stored = await bytesAtTheStoreBoundary(inputWithCanaries(), Object.values(CANARIES));

    for (const canary of Object.values(CANARIES)) expect(stored).not.toContain(canary);
    // A redaction that corrupted the document would make it unrecoverable to the reconciler.
    const parsed = JSON.parse(stored) as { executionId: string; evidencePartial: boolean };
    expect(parsed.executionId).toBe(FIXTURE_INPUT.executionId);
    expect(parsed.evidencePartial).toBe(true);
  });

  it('scrubs a value that JSON would otherwise escape out of a plain text search', async () => {
    // The first pass exists for this: a value containing a quote is `\"` in the finished document,
    // so scrubbing only the serialized text would miss it entirely.
    const awkward = 'canary-with-a-"quote"-and-a-\\backslash-3e8a11';
    const input: ResultManifestInput = {
      ...FIXTURE_INPUT,
      outcome: { result: 'ERROR', errorCode: 'TIMEOUT', errorMessage: `failed: ${awkward}` },
    };

    expect(serialize(input, NULL_REDACTOR)).toContain('canary-with-a-');
    const stored = await bytesAtTheStoreBoundary(input, [awkward]);

    expect(stored).not.toContain('canary-with-a-');
  });
});

function inputWithCanaries(): ResultManifestInput {
  // Shape 1: an innocently named local, carried into a field nobody associates with secrets.
  const displayLabel = `run for ${CANARIES.innocentLocal}`;
  // Shape 2: the message of a real throwable, which is how a resolved value actually escapes.
  const thrown = new Error(`navigation to ${CANARIES.throwableMessage} timed out`);
  return {
    ...FIXTURE_INPUT,
    runnerInstanceId: displayLabel,
    outcome: { result: 'ERROR', errorCode: 'TIMEOUT', errorMessage: thrown.message },
    // Shape 3: inside a runtime-version string.
    runtimeVersions: {
      ...FIXTURE_INPUT.runtimeVersions,
      image: `studio-runner:0.1.0+${CANARIES.runtimeVersion}`,
    },
  };
}

describe('guided recording manifest (STUDIO-OBS-013 AC-5, AR-1 R3 guidedManifest)', () => {
  it('serializes the guided body in wire order through the same redact-twice serializer, with the constant disclosure', () => {
    const body = buildGuidedRecordingManifest({ sessionId: 'session-1', recordingId: 'rec-1', workerId: 'worker-one', ownerFence: 2, evidenceState: 'STORED', evidencePartial: true, videoKey: 'studio/CSI-1/guided/session-1.webm', manifestKey: 'studio/CSI-1/guided/session-1.manifest.json', timings: [{ kind: 'action', stepId: 'nav', admissionId: 'a-1', ordinal: 0, startMs: 3, endMs: null }] });
    const text = new TextDecoder().decode(serializeResultManifest(body, NULL_REDACTOR));
    expect(Object.keys(JSON.parse(text) as object)).toEqual(['schemaVersion', 'kind', 'sessionId', 'recordingId', 'workerId', 'ownerFence', 'evidenceState', 'evidencePartial', 'videoKey', 'manifestKey', 'timings', 'disclosure']);
    expect(JSON.parse(text)).toMatchObject({ schemaVersion: RESULT_MANIFEST_SCHEMA_VERSION, kind: 'guidedRecording', evidencePartial: true, disclosure: GUIDED_RECORDING_DISCLOSURE });
    expect(GUIDED_RECORDING_DISCLOSURE).toContain('masked dots');
    expect(GUIDED_RECORDING_DISCLOSURE).toContain('not protected by this recording');
    const redacted = new TextDecoder().decode(serializeResultManifest(body, createRedactor(['worker-one'])));
    expect(redacted).not.toContain('worker-one');
  });
});
