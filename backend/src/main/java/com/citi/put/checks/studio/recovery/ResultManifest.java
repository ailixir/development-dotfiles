package com.citi.put.checks.studio.recovery;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import java.time.Instant;
import java.util.Map;

/**
 * The terminal result manifest the runner writes to object storage before it reports (§5.3).
 *
 * <p>It exists so that a lost delivery is not a lost result: the API derives the key from immutable
 * execution identity, reads it at that known key, and gets the <b>real</b> outcome in place of an
 * ambiguous timeout.
 *
 * <p><b>Widened by story 10.14 to what §5.3 actually requires</b> — <i>"attempt/revision identity,
 * result, timings, runtime versions, and evidence state"</i>. Until then it carried the result, the
 * timings, the video key and the evidence state, and neither identity nor runtime versions: a
 * defect against a landed normative source rather than a contract question, which is why @po ruled
 * the widening ungated while the <em>declaration</em> of this body in {@code openapi.yaml} stays
 * open as AC-7b.
 *
 * <p><b>This body is not declared in the frozen contract</b>, and it is the only runner-produced
 * body that is not (ADR-002 §6.2). The mechanism holding the two sides together until @architect
 * rules is one fixture, generated by the runner's own serializer and committed once: {@code
 * studio-runner/test/fixtures/result-manifest.json}. The runner suite asserts its serializer still
 * produces those bytes; {@code ResultManifestFixtureTest} deserializes that same file through this
 * record and asserts every component. A fixture is checkable, and it is not a contract — which
 * AC-7b says out loud rather than papering over.
 *
 * @param schemaVersion the version these bytes were written under; read before anything else
 * @param executionId identity embedded in the body, used as <b>defence in depth</b> over the
 *     derived key and never as a substitute for it (AC-7a). {@link FinalizationReconciler} refuses
 *     a manifest whose embedded identity does not match the key it was read from
 * @param errorCode the runner's own code, which is recorded and never copied into {@code
 *     error_code} — the same rule that governs a delivered report (AC-16)
 * @param evidencePartial whether the recording covers the whole browser session (ADR-002 §17). It
 *     is never derived from {@code outcome} in either direction, by either component
 */
@JsonIgnoreProperties(ignoreUnknown = true)
public record ResultManifest(
    Integer schemaVersion,
    String executionId,
    String attemptId,
    String revisionId,
    String artifactHash,
    String runnerInstanceId,
    String outcome,
    String errorCode,
    String errorMessage,
    Instant browserStartedAt,
    Instant endedAt,
    Integer durationMs,
    Map<String, String> runtimeVersions,
    String videoKey,
    String manifestKey,
    String evidenceState,
    Boolean evidencePartial) {}
