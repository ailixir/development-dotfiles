package com.citi.put.checks.studio.recovery;

import static org.assertj.core.api.Assertions.assertThat;

import com.fasterxml.jackson.databind.DeserializationFeature;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.json.JsonMapper;
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.UUID;
import org.junit.jupiter.api.Test;

/**
 * Story 10.14 AC-7a — the runner's bytes, read by this record.
 *
 * <p>The terminal result manifest is the one runner-produced body the frozen contract does not
 * declare (ADR-002 §6.2); AC-7b escalates that to @architect and this story adds no schema on its
 * own authority. What it does instead is refuse the arrangement §15.6 names as the cause of INT-4 —
 * two hand-maintained copies of one shape in two languages — and replace it with <b>one
 * artefact</b>:
 *
 * <ul>
 *   <li>{@code studio-runner/test/fixtures/result-manifest.json} is generated by the runner's own
 *       {@code serializeResultManifest} and committed once;
 *   <li>{@code test/run/manifest.test.ts} asserts that serializer still produces those bytes;
 *   <li>this test deserializes the same file through {@link ResultManifest} and asserts every
 *       component.
 * </ul>
 *
 * <p>If either side moves, one of the two tests goes red. That is weaker than a contract and it is
 * stated as such: a fixture is checkable, but nothing stops a third consumer from guessing.
 */
class ResultManifestFixtureTest {

  /** Generated by the runner's serializer. Never hand-edited on this side. */
  private static final Path FIXTURE =
      Path.of("..", "studio-runner", "test", "fixtures", "result-manifest.json");

  private final ObjectMapper mapper =
      JsonMapper.builder()
          .addModule(new JavaTimeModule())
          .disable(DeserializationFeature.ADJUST_DATES_TO_CONTEXT_TIME_ZONE)
          .build();

  private ResultManifest read() throws IOException {
    return mapper.readValue(
        Files.readString(FIXTURE, StandardCharsets.UTF_8), ResultManifest.class);
  }

  @Test
  void everyComponentOfSection53SurvivesTheCrossingFromTypeScriptToJava() throws IOException {
    ResultManifest manifest = read();

    assertThat(manifest.schemaVersion()).isEqualTo(1);

    // §5.3 "attempt/revision identity".
    assertThat(manifest.executionId()).isEqualTo("9f1d5c2e-3a4b-4c5d-8e6f-7a8b9c0d1e2f");
    assertThat(manifest.attemptId()).isEqualTo("1c2d3e4f-5a6b-4c7d-8e9f-0a1b2c3d4e5f");
    assertThat(manifest.revisionId()).isEqualTo("2d3e4f5a-6b7c-4d8e-9f0a-1b2c3d4e5f60");
    assertThat(manifest.artifactHash())
        .isEqualTo("sha256:9a7d1c0b5e3f2a4c6d8e0f1a2b3c4d5e6f708192a3b4c5d6e7f8091a2b3c4d5e");
    assertThat(manifest.runnerInstanceId()).isEqualTo("studio-runner-0");
    // Parseable as the UUIDs the key derivation uses, not merely as strings.
    assertThat(UUID.fromString(manifest.executionId())).isNotNull();
    assertThat(UUID.fromString(manifest.attemptId())).isNotNull();

    // §5.3 "result".
    assertThat(manifest.outcome()).isEqualTo("ERROR");
    assertThat(manifest.errorCode()).isEqualTo("TIMEOUT");
    assertThat(manifest.errorMessage())
        .isEqualTo("The total browser runtime deadline was reached.");

    // §5.3 "timings". The instants cross the language boundary, not just the strings.
    assertThat(manifest.browserStartedAt()).isEqualTo(Instant.parse("2026-09-11T10:00:02Z"));
    assertThat(manifest.endedAt()).isEqualTo(Instant.parse("2026-09-11T10:02:02.500Z"));
    assertThat(manifest.durationMs()).isEqualTo(120_500);

    // §5.3 "runtime versions" — absent from this record until story 10.14.
    assertThat(manifest.runtimeVersions())
        .containsEntry("playwright", "1.63.0")
        .containsEntry("chromium", "141.0.7390.37")
        .containsEntry("node", "22.20.0")
        .containsEntry("image", "studio-runner:0.1.0")
        .containsEntry("executor", "1.0.0")
        .containsEntry("validatorSchema", "1.0.0");

    // §5.3 "evidence state".
    assertThat(manifest.evidenceState()).isEqualTo("STORED");
    assertThat(manifest.evidencePartial()).isTrue();
    assertThat(manifest.videoKey()).endsWith(".webm");
    assertThat(manifest.manifestKey()).endsWith(".result.json");
  }

  /**
   * The control: no component of the record is left null by the crossing.
   *
   * <p>Without it, a field the runner renamed would simply deserialize as {@code null} and every
   * targeted assertion above that happened not to cover it would stay green. This one fails the
   * moment a component stops being populated, whatever its name.
   */
  @Test
  void noComponentIsLeftNullByTheCrossing() throws IOException {
    ResultManifest manifest = read();

    assertThat(manifest.schemaVersion()).isNotNull();
    assertThat(manifest.executionId()).isNotNull();
    assertThat(manifest.attemptId()).isNotNull();
    assertThat(manifest.revisionId()).isNotNull();
    assertThat(manifest.artifactHash()).isNotNull();
    assertThat(manifest.runnerInstanceId()).isNotNull();
    assertThat(manifest.outcome()).isNotNull();
    assertThat(manifest.errorCode()).isNotNull();
    assertThat(manifest.errorMessage()).isNotNull();
    assertThat(manifest.browserStartedAt()).isNotNull();
    assertThat(manifest.endedAt()).isNotNull();
    assertThat(manifest.durationMs()).isNotNull();
    assertThat(manifest.runtimeVersions()).isNotNull().isNotEmpty();
    assertThat(manifest.videoKey()).isNotNull();
    assertThat(manifest.manifestKey()).isNotNull();
    assertThat(manifest.evidenceState()).isNotNull();
    assertThat(manifest.evidencePartial()).isNotNull();
  }

  /**
   * AC-1 — the two key derivations agree, asserted rather than assumed.
   *
   * <p>Two derivations of one string in two languages is the arrangement ADR-002 §15.6 names as the
   * cause of INT-4. The runner never derives a key — it echoes the job's — but the <b>API</b>
   * derives both, and the fixture carries the pair the runner was given for this identity. If
   * {@link ManifestKeys} and the job builder ever disagree, recovery reads an object nobody wrote.
   */
  @Test
  void theKeysInTheFixtureAreTheKeysManifestKeysDerivesForThatIdentity() throws IOException {
    ResultManifest manifest = read();

    ResultManifestStore.ExecutionIdentity identity =
        new ResultManifestStore.ExecutionIdentity(
            "60001",
            UUID.fromString("00000000-0000-4000-8000-000000003b9c"),
            UUID.fromString(manifest.executionId()),
            UUID.fromString(manifest.attemptId()));

    // The fixture's CSI and test id are embedded in its keys rather than in its body, because the
    // manifest carries attempt/revision identity and not the whole address (§5.3).
    assertThat(manifest.videoKey())
        .isEqualTo(
            "studio/60001/3b9c/" + manifest.executionId() + "/" + manifest.attemptId() + ".webm");
    assertThat(manifest.manifestKey())
        .isEqualTo(
            "studio/60001/3b9c/"
                + manifest.executionId()
                + "/"
                + manifest.attemptId()
                + ".result.json");

    // And the API's derivation has the same shape, component for component, for a real identity.
    assertThat(ManifestKeys.videoKey(identity))
        .isEqualTo(
            "studio/60001/"
                + identity.testId()
                + "/"
                + manifest.executionId()
                + "/"
                + manifest.attemptId()
                + ".webm");
    assertThat(ManifestKeys.manifestKey(identity)).endsWith(".result.json");
    assertThat(ManifestKeys.manifestKey(identity))
        .isEqualTo(
            ManifestKeys.videoKey(identity)
                    .substring(0, ManifestKeys.videoKey(identity).length() - 5)
                + ".result.json");
  }
}
